def read_mode_table(data, address, *, base=BASE, limit=64):
    """Bound sentinel lookup; never silently read the following mode table."""
    rows = []
    for index in range(limit):
        off = address-base+index*12
        require(0 <= off and off+12 <= len(data), 'truncated mode table')
        row = struct.unpack_from('<IIHH', data, off)
        if row[0] == 36:
            return rows
        require(row[0] < 36, 'invalid mode selector result')
        rows.append(row)
    raise ValueError('missing mode table sentinel')


def select_mode(primary, fallback, mode, rate, variant):
    for row in primary:
        if row[1:] == (mode,rate,variant):
            return dict(result=row[0],source='primary',table_rate=row[2])
    for row in fallback:
        if (row[1],row[3]) == (mode,variant):
            return dict(result=row[0],source='fallback_ignores_rate',table_rate=row[2])
    return dict(result=36,source='unmatched',table_rate=None)


def camera_output_nominal_hz(pll_word, predivider_word, divider_word):
    """Reproduce the integer getter branch for CLK_CAMOUT mux=1.

    Assumes the programmed PLL state and enabled path; this is neither a
    measurement nor a TG clock model. Preserve truncation before multiplication.
    """
    for word in (pll_word, predivider_word, divider_word):
        require(0 <= word <= 0xffffffff, 'clock word outside uint32')
    factor = ((pll_word >> 16) & 0x7f)*10
    if not (pll_word & 4):
        factor >>= 1
    factor //= ((pll_word >> 4) & 3)+1
    pll_hz = factor*2400000
    return pll_hz//(2*(predivider_word+1))//(2*(divider_word+1))


def sensor_model_time(clock_word, ticks):
    """Native 0x6050dff5 arithmetic, not a measured TG clock or readout model."""
    require(0 <= clock_word <= 0xffffffff and 0 <= ticks <= 0xffffffff,
            'timing word outside uint32')
    divisor = clock_word >> 7
    require(divisor != 0, 'zero sensor timing divisor')
    return ((2*ticks) & 0xffffffff)//divisor


def rebased_marker_offset(period, phase, center):
    """Native timing-record +32 rewrite; preserve unsigned subtraction/shift."""
    require(0 <= period <= 0xffffffff and 0 <= phase <= 0xffffffff and
            0 <= center <= 0xffff, 'invalid rebase input width')
    return (phase + (((period-phase) & 0xffffffff) >> 1) + center) & 0xffffffff


def ordinary_center_gate(normalized_rate, accumulator, flag53=0, flag54=0, flag700=0):
    """0x6091dd4c..0x6091dda0 after normalization; excludes the special branch.

    Return (accepted, next uint16 accumulator). The <=60 branch clears d0
    for the accumulator store, then sets d0=1 before returning.
    """
    require(0 <= normalized_rate <= 0xffff and 0 <= accumulator <= 0xffff,
            'invalid center-gate halfword')
    require(all(0 <= x <= 0xff for x in (flag53, flag54, flag700)),
            'invalid center-gate byte')
    if normalized_rate <= 60:
        return True, 0
    updated = (accumulator + 240//normalized_rate) & 0xffff
    if flag53 != 1 and flag54 == 1 and flag700 == 0:
        return True, 0
    return (True, 0) if updated >= 4 else (False, updated)


